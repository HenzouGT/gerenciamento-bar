    private void btnCriarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCriarActionPerformed
        try {
            CriarProdutoDTO dados = 
                new CriarProdutoDTO(
                    txtNome.getText(),
                    obterPrecoFormulario(),
                    (Integer) spnQuantidade.getValue(),
                    chkAtivo.isSelected()
                );
        
            produtoService.criar(dados);
            
            JOptionPane.showMessageDialog(this, "Produto cadastrado com sucesso.");
            
            limparFormulario();
            carregarProdutos();
        } catch (RuntimeException e) {
            exibirErro(e);
        }                                     
    }//GEN-LAST:event_btnCriarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (produtoSelecionadoId == null) {
            JOptionPane.showMessageDialog(this, "Selecione um Produto.");
            return;
        }
        
        try {
            EditarProdutoDTO dados =
                new EditarProdutoDTO(
                    txtNome.getText(),
                    obterPrecoFormulario(),
                    (Integer) spnQuantidade.getValue()
                );
            
            produtoService.editar(produtoSelecionadoId, dados);
            
            JOptionPane.showMessageDialog(this, "Produto editado.");
            
            limparFormulario();
            carregarProdutos();
        
        } catch (RuntimeException e) {
            exibirErro(e);
        } 
                
    }//GEN-LAST:event_btnEditarActionPerformed

