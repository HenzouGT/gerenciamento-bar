    private void configurarComponentes() {
        spnQuantidade.setModel(
            new javax.swing.SpinnerNumberModel(0, 0, Integer.MAX_VALUE, 1)
        );

        DecimalFormat formato = (DecimalFormat)
        NumberFormat.getNumberInstance(new Locale("pt", "BR"));

        formato.setParseBigDecimal(true);
        formato.setMinimumFractionDigits(2);
        formato.setMaximumFractionDigits(2);

        NumberFormatter formatter = new NumberFormatter(formato);
        formatter.setValueClass(BigDecimal.class);
        formatter.setMinimum(new BigDecimal("0.01"));
        formatter.setAllowsInvalid(true);
        formatter.setCommitsOnValidEdit(true);

        ftxtPreco.setFormatterFactory(
            new DefaultFormatterFactory(formatter)
        );
        
        tblProdutos
            .getSelectionModel()
            .addListSelectionListener(event -> {
                if (!event.getValueIsAdjusting()) {
                    carregarProdutoSelecionado();
                }
            });
    }

    private BigDecimal obterPrecoFormulario() {
        try {
            ftxtPreco.commitEdit();
            return (BigDecimal) ftxtPreco.getValue();
        } catch (ParseException e) {
            throw new IllegalArgumentException("Informe um preço válido.");
        }
    }
    
    private void carregarProdutos() {
        List<ResumoProdutoDTO> produtos = produtoService.buscarTodos();
        
        DefaultTableModel modelo = (DefaultTableModel) tblProdutos.getModel();
        
        modelo.setRowCount(0);
        
        for (ResumoProdutoDTO produto : produtos) {
            modelo.addRow(new Object[]{
                produto.id(),
                produto.nome(),
                produto.preco(),
                produto.quantidadeEstoque(),
                produto.ativo()
            });
        }
    }
    
    private void limparFormulario() {
        produtoSelecionadoId = null;
        
        txtNome.setText("");
        ftxtPreco.setValue(null);
        spnQuantidade.setValue(0);
        chkAtivo.setSelected(false);
        
        chkAtivo.setEnabled(true);
        lblAtivo.setEnabled(true);
        
        tblProdutos.clearSelection();        
        txtNome.requestFocusInWindow();
    }
    
    private void carregarProdutoSelecionado() {
        int linhaSelecionada = tblProdutos.getSelectedRow();
        
        if (linhaSelecionada < 0) {
            produtoSelecionadoId = null;
            return;
        } 
        
        int linhaModelo = tblProdutos.convertRowIndexToModel(
            linhaSelecionada
        );
        
        produtoSelecionadoId = ((Number) tblProdutos
            .getModel()
            .getValueAt(linhaModelo, 0))
            .longValue();
        
        try {
            produtoService
                .buscarPorId(produtoSelecionadoId)
                .ifPresent(produto -> {
                    txtNome.setText(produto.nome());
                    ftxtPreco.setValue(produto.preco());
                    spnQuantidade.setValue(produto.quantidadeEstoque());
                    chkAtivo.setSelected(produto.ativo());
                    
                    chkAtivo.setEnabled(false);
                    lblAtivo.setEnabled(false);
                });
            
        } catch (RuntimeException e) {
            exibirErro(e);
        }
    }
    
    private void exibirErro(RuntimeException e) {
        String mensagem = e.getMessage();
        
        if (mensagem == null || mensagem.isBlank()) {
            mensagem = "Ocorreu um erro inesperado.";
        }
        
        JOptionPane.showMessageDialog(
            this,
            mensagem,
            "Erro",
            JOptionPane.ERROR_MESSAGE
        );
    }

