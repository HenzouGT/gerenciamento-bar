    private void btnDesativarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDesativarActionPerformed
        if (funcionarioSelecionadoId == null) {
            JOptionPane.showMessageDialog(this, "Selecione um funcionário.");
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
            this,
            "Deseja desativar este funcionário?",
            "Confirmação",
            JOptionPane.YES_NO_OPTION
        );

        if (resposta == JOptionPane.YES_OPTION) {
            try {
                funcionarioService.desativar(funcionarioSelecionadoId);

                limparFormulario();
                carregarFuncionarios();

                JOptionPane.showMessageDialog(this, "Funcionário desativado.");
                
            } catch (RuntimeException e) {
                exibirErro(e);
            }
        }
    }//GEN-LAST:event_btnDesativarActionPerformed

