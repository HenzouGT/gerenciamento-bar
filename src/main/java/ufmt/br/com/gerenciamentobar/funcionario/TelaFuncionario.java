    private void configurarComponentes() {
        cmbCargo.setModel(new DefaultComboBoxModel<>(Cargo.values()));
        
        tblFuncionarios
            .getSelectionModel()
            .addListSelectionListener(event -> {
                if (!event.getValueIsAdjusting()) {
                    carregarFuncionarioSelecionado();
                }
            });            
        tblFuncionarios.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
    }

    private void carregarFuncionarios() {
        List<ResumoFuncionarioDTO> funcionarios = funcionarioService.buscarTodos();

        DefaultTableModel modelo = (DefaultTableModel) tblFuncionarios.getModel();

        modelo.setRowCount(0);

        for (ResumoFuncionarioDTO funcionario : funcionarios) {
            modelo.addRow(new Object[]{
                funcionario.id(),
                funcionario.nome(),
                funcionario.cpf(),
                funcionario.telefone(),
                funcionario.cargo(),
                funcionario.ativo()
            });
        }
    }
    
    private void limparFormulario() {
        funcionarioSelecionadoId = null;

        txtNome.setText("");
        txtCpf.setText("");
        txtTelefone.setText("");        
        txtSenha.setText("");
        txtSenha.setEnabled(true);
        lblSenha.setEnabled(true);

        cmbCargo.setSelectedIndex(0);
        tblFuncionarios.clearSelection();

        txtNome.requestFocusInWindow();        
    }
    
    private void carregarFuncionarioSelecionado() {
        int linhaSelecionada = tblFuncionarios.getSelectedRow();

        if (linhaSelecionada < 0) {
            funcionarioSelecionadoId = null;
            return;
        }

        int linhaModelo = tblFuncionarios.convertRowIndexToModel(
            linhaSelecionada
        );

        funcionarioSelecionadoId = ((Number) tblFuncionarios
            .getModel()
            .getValueAt(linhaModelo, 0))
            .longValue();

        try {
            funcionarioService
                .buscarPorId(funcionarioSelecionadoId)
                .ifPresent(funcionario -> {
                    txtNome.setText(funcionario.nome());
                    txtCpf.setText(funcionario.cpf());
                    txtTelefone.setText(funcionario.telefone());
                    cmbCargo.setSelectedItem(funcionario.cargo());

                    txtSenha.setText("");
                    txtSenha.setEnabled(false);
                    lblSenha.setEnabled(false);
                });

        } catch (RuntimeException e) {
            exibirErro(e);
        }
    }

    private void exibirErro(RuntimeException e) {
        String mensagem = e.getMessage();

        if (mensagem == null || mensagem.isBlank()) {
            mensagem = "Ocorreu um erro inesperado.";
        }

        JOptionPane.showMessageDialog(
            this,
            mensagem,
            "Erro",
            JOptionPane.ERROR_MESSAGE
        );
    }

