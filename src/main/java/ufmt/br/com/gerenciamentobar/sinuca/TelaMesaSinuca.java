    private void configurarComponentes() {
        spnNumero.setModel(
            new javax.swing.SpinnerNumberModel(0, 0, Integer.MAX_VALUE, 1)
        );

        DecimalFormat formato = (DecimalFormat)
        NumberFormat.getNumberInstance(new Locale("pt", "BR"));

        formato.setParseBigDecimal(true);
        formato.setMinimumFractionDigits(2);
        formato.setMaximumFractionDigits(2);

        NumberFormatter formatter = new NumberFormatter(formato);
        formatter.setValueClass(BigDecimal.class);
        formatter.setMinimum(new BigDecimal("0.01"));
        formatter.setAllowsInvalid(true);
        formatter.setCommitsOnValidEdit(true);

        ftxtValorHora.setFormatterFactory(
            new DefaultFormatterFactory(formatter)
        );
        
        tblMesasSinuca
            .getSelectionModel()
            .addListSelectionListener(event -> {
                if (!event.getValueIsAdjusting()) {
                    carregarMesaSinucaSelecionada();
                }
            });
    }
    
    private BigDecimal obterValorHoraFormulario() {
        try {
            ftxtValorHora.commitEdit();
            return (BigDecimal) ftxtValorHora.getValue();
        } catch (ParseException e) {
            throw new IllegalArgumentException("Informe um valor de hora válido.");
        }
    }
    
    private void carregarMesasSinuca() {
        List<ResumoMesaSinucaDTO> mesasSinuca = mesaSinucaService.buscarTodos();
        
        DefaultTableModel modelo = (DefaultTableModel) tblMesasSinuca.getModel();
        
        modelo.setRowCount(0);
        
        for (ResumoMesaSinucaDTO mesaSinuca : mesasSinuca) {
            modelo.addRow(new Object[]{
                mesaSinuca.id(),
                mesaSinuca.numero(),
                mesaSinuca.valorHora(),
                mesaSinuca.status()
            });
        }
    }
    
    private void limparFormulario() {
        mesaSinucaSelecionadaId = null;
        
        spnNumero.setValue(0);
        ftxtValorHora.setValue(null);
        
        tblMesasSinuca.clearSelection();
        spnNumero.requestFocusInWindow();
    }
    
    private void carregarMesaSinucaSelecionada() {
        int linhaSelecionada = tblMesasSinuca.getSelectedRow();
        
        if (linhaSelecionada < 0) {
            mesaSinucaSelecionadaId = null;
            return;
        }
        
        int linhaModelo = tblMesasSinuca.convertRowIndexToModel(
            linhaSelecionada
        );
        
        mesaSinucaSelecionadaId = ((Number) tblMesasSinuca
            .getModel()
            .getValueAt(linhaModelo, 0))
            .longValue();
        
        try {
            mesaSinucaService
                .buscarPorId(mesaSinucaSelecionadaId)
                .ifPresent(mesaSinuca -> {
                    spnNumero.setValue(mesaSinuca.numero());
                    ftxtValorHora.setValue(mesaSinuca.valorHora());
                });
            
        } catch (RuntimeException e) {
            exibirErro(e);
        }
    }
    
    private void exibirErro(RuntimeException e) {
        String mensagem = e.getMessage();
        
        if (mensagem == null || mensagem.isBlank()) {
            mensagem = "Ocorreu um erro inesperado.";
        }
        
        JOptionPane.showMessageDialog(
            this,
            mensagem,
            "Erro",
            JOptionPane.ERROR_MESSAGE
        );
    }    

